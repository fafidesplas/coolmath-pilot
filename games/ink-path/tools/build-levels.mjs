// Source of the slice levels until the phase 3 editor exists. Each level's two
// reference lines are designer paths drawn through the real pen (lazy string,
// spacing, blocked areas, RDP), so they are exactly what a player's hand could make.
//   node tools/build-levels.mjs    writes levels/w1l0N.js
import { writeFileSync } from 'node:fs';
import { parseLevel, blockedAt } from '../src/level.js';
import { penStroke } from '../src/pen.js';

const arc = (x0, y0, x1, y1, sag, n = 30) => {
  const p = [];
  for (let i = 0; i <= n; i++) { const t = i / n; p.push([x0 + (x1 - x0) * t, y0 + (y1 - y0) * t + sag * 4 * t * (1 - t)]); }
  return p;
};
// A hand-drawn wobble on top of an arc.
const wavy = (x0, y0, x1, y1, sag, amp, waves) =>
  arc(x0, y0, x1, y1, sag, 120).map(([x, y], i) => [x, y + amp * Math.sin(i / 120 * Math.PI * 2 * waves)]);
const up10 = v => Math.ceil(v / 10) * 10;

const LEVELS = [
  {
    data: {
      id: 'w1l01', name: 'First Line', ink: 800, marks: { three: 600, two: 700 },   // by hand: tracing the guide earns 3★
      balls: [{ x: 340, y: 90 }],
      cups: [{ x: 1080, y: 462, w: 104, board: 140, boardSide: 'right' }],
      walls: [[[880, 540], [1280, 540], [1280, 640], [880, 640]]],
    },
    easy: wavy(300, 150, 730, 400, 140, 12, 2),
    gold: arc(310, 150, 720, 380, 120),
    guide: true,
  },
  {
    data: {
      id: 'w1l02', name: 'Bridge', ink: 480, marks: { three: 360, two: 420 }, intro: 'meter',
      balls: [{ x: 110, y: 80 }],
      cups: [{ x: 1000, y: 394, w: 104 }],
      walls: [
        [[0, 250], [420, 370], [420, 640], [0, 640]],
        [[740, 394], [934, 394], [934, 640], [740, 640]],
        [[1066, 394], [1280, 394], [1280, 640], [1066, 640]],
        [[936, 472], [1064, 472], [1064, 640], [936, 640]],
      ],
    },
    easy: [[426, 376], [600, 380], [735, 384], [860, 384]],
    gold: [[426, 376], [725, 378]],
  },
  {
    data: {
      id: 'w1l03', name: 'Less Is More', ink: 0, marks: null, intro: 'stars',      // marks from the formula (GDD 3.8)
      balls: [{ x: 360, y: 80 }],
      cups: [{ x: 1040, y: 522, w: 104, board: 150, boardSide: 'right' }],
      walls: [
        [[440, 260], [900, 450], [900, 472], [440, 282]],
        [[860, 600], [1280, 600], [1280, 640], [860, 640]],
      ],
    },
    easy: [[330, 125], [660, 335]],
    gold: [[350, 124], [420, 224]],
  },
];

const fmt = v => JSON.stringify(v);
for (const L of LEVELS) {
  const d = { ...L.data };
  const lv = parseLevel({ ...d, ink: 5000, marks: d.marks || {} });
  const rec = path => {
    const { result } = penStroke((x, y) => blockedAt(lv, x, y), 5000, path);
    return { ink: Math.round(result.ink), pts: result.pts };
  };
  const easy = rec(L.easy), gold = rec(L.gold);
  if (!d.marks) {
    const three = up10(gold.ink * 1.15);
    d.marks = { three, two: up10((three + easy.ink) / 2) };
    d.ink = up10(easy.ink * 1.25);
  }
  if (L.guide) d.guide = gold.pts;
  d.refs = { easy, gold };
  const lines = [
    `// ${d.name} (GDD 6). Generated by tools/build-levels.mjs; edit there, not here.`,
    'export default {',
    ...Object.entries(d).map(([k, v]) => k === 'walls'
      ? `  walls: [\n${v.map(w => `    ${fmt(w)},`).join('\n')}\n  ],`
      : k === 'refs'
        ? `  refs: {\n    easy: ${fmt(v.easy)},\n    gold: ${fmt(v.gold)},\n  },`
        : `  ${k}: ${fmt(v)},`),
    '};',
    '',
  ];
  writeFileSync(new URL(`../levels/${d.id}.js`, import.meta.url), lines.join('\n'));
  console.log(`${d.id}: pot ${d.ink}, ★★★ ${d.marks.three}, ★★ ${d.marks.two}, easy ${easy.ink} px (${easy.pts.length} pts), gold ${gold.ink} px (${gold.pts.length} pts)`);
}
