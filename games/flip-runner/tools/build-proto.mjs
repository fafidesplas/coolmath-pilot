// Builds levels/proto.js: the forms prototype (Flip → Glider → Flip → Twin → Flip).
//   node tools/build-proto.mjs
import { writeFileSync } from 'node:fs';

const COLS = 340, ROWS = 16;
const g = Array.from({ length: ROWS }, () => Array(COLS).fill('.'));
const fill = (c0, c1, r0, r1, ch = '#') => { for (let c = c0; c <= c1; c++) for (let r = r0; r <= r1; r++) g[r][c] = ch; };
// Corridor helper: solid above `top` and from `bottom` down.
const corridor = (c0, c1, top, bottom) => { fill(c0, c1, 0, top - 1); fill(c0, c1, bottom, ROWS - 1); };
const fs = (c0, c1, row = 10) => fill(c0, c1, row, row, '^');
const cs = (c0, c1, row = 5) => fill(c0, c1, row, row, 'v');

// 1. Flip warm-up (rows 5–10)
corridor(0, 73, 5, 11);
fs(14, 16); cs(23, 25); fs(32, 34);
fill(40, 45, 11, 15, '.');
cs(50, 52); fs(58, 60);

// 2. Glider room (rows 1–14) with pillars to weave through
corridor(74, 149, 1, 15);
const gaps = [[84, 2, 5], [95, 9, 12], [106, 4, 7], [117, 10, 13], [128, 3, 6], [139, 6, 9]];
for (const [c, top, bot] of gaps) { fill(c, c + 1, 1, top - 1); fill(c, c + 1, bot + 1, 14); }

// 3. Flip again
corridor(150, 191, 5, 11);
fs(166, 168); cs(175, 177); fs(184, 186);

// 4. Twin: lane A rows 1–5, band rows 6–8, lane B rows 9–13
corridor(192, 195, 1, 11);
corridor(196, 280, 1, 14);
fill(196, 280, 6, 8);
const A = { ceil: 1, floor: 5 }, Bl = { ceil: 9, floor: 13 };
cs(205, 206, A.ceil); cs(205, 206, Bl.ceil);
fs(214, 215, A.floor);
cs(222, 223, Bl.ceil);
fs(230, 232, A.floor); cs(236, 237, Bl.ceil);
fs(244, 245, Bl.floor); cs(250, 251, A.ceil);
fs(258, 259, A.floor); fs(258, 259, Bl.floor);
cs(266, 267, Bl.ceil);
corridor(281, 289, 1, 11);

// 5. Flip finale
corridor(290, COLS - 1, 5, 11);
fs(300, 302); cs(310, 312);

const level = {
  id: 'proto',
  name: 'Forms Prototype',
  speed: 440,
  start: { x: 3, y: 10, gravity: 1 },
  tiles: g.map(r => r.join('')),
  objects: [
    { type: 'hint', x: 9 },
    { type: 'portal', x: 70, form: 'glider' },
    { type: 'hint', x: 68, label: 'HOLD!' },
    { type: 'portal', x: 152, form: 'flip' },
    { type: 'portal', x: 199, form: 'twin', lane: 11 },
    { type: 'hint', x: 197, label: 'TWINS!' },
    { type: 'portal', x: 281, form: 'flip' },
    { type: 'flag', x: 66, y: 10 },
    { type: 'flag', x: 158, y: 10 },
    { type: 'flag', x: 240, y: 5 },
    { type: 'star', x: 101, y: 12 },
    { type: 'star', x: 227, y: 5 },
    { type: 'star', x: 306, y: 10 },
    { type: 'goal', x: 325 },
  ],
};

const body = JSON.stringify(level, null, 2).replace(/"tiles": \[[^\]]*\]/s, () => `"tiles": [\n${level.tiles.map(r => `    '${r}',`).join('\n')}\n  ]`);
writeFileSync(new URL('../levels/proto.js', import.meta.url),
  `// Forms prototype: Flip, Glider and Twin in one level. Generated by tools/build-proto.mjs.\nexport default ${body};\n`);
console.log('wrote levels/proto.js', COLS, 'columns');
