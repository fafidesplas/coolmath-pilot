// Draw a 32×16 level on a grid, then write it as a level module.
//   const g = new Grid();           // border and a floor at row 12
//   g.fill(8, 10, 10, 11);          // a block of solid tiles
//   g.put(5, 11, '^');
//   writeLevel({ id, name, spawn, exit, bolts, objects }, g);
import { writeFileSync, existsSync, readFileSync } from 'node:fs';

export const COLS = 32, ROWS = 16;

export class Grid {
  constructor(floorRow = 12) {
    this.c = Array.from({ length: ROWS }, () => Array(COLS).fill('.'));
    this.fill(0, COLS - 1, 0, 0);            // ceiling
    this.fill(0, 0, 0, ROWS - 1);            // left wall
    this.fill(COLS - 1, COLS - 1, 0, ROWS - 1);
    this.fill(0, COLS - 1, floorRow, ROWS - 1);
  }
  fill(c0, c1, r0, r1, ch = '#') { for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) this.c[r][c] = ch; return this; }
  put(c, r, ch) { this.c[r][c] = ch; return this; }
  rows() { return this.c.map(r => r.join('')); }
  // print with column numbers, to check a design by eye
  show() {
    let head = '    '; for (let c = 0; c < COLS; c++) head += c % 10 === 0 ? String(c / 10) : ' ';
    console.log(head); this.rows().forEach((r, i) => console.log(String(i).padStart(2) + '  ' + r));
  }
}

// par comes from the stored solution times (par = recorded time × 1.25, rounded up), if they exist.
export function parFor(id) {
  const out = { coop: 60, solo: 90 };
  for (const mode of ['coop', 'solo']) {
    const f = new URL(`../levels/solutions/${id}.${mode}.json`, import.meta.url);
    if (existsSync(f)) { const r = JSON.parse(readFileSync(f, 'utf8')); if (r.time) out[mode] = Math.ceil(r.time * 1.25); }
  }
  return out;
}

export function writeLevel(spec, grid) {
  const level = { id: spec.id, name: spec.name, par: parFor(spec.id), tiles: grid.rows(), spawn: spec.spawn, exit: spec.exit, bolts: spec.bolts, objects: spec.objects || [] };
  if (spec.tutorialDone) level.tutorialDone = true;
  const body = JSON.stringify(level, null, 2).replace(/"tiles": \[[^\]]*\]/s, () => `"tiles": [\n${level.tiles.map(r => `    '${r}',`).join('\n')}\n  ]`);
  writeFileSync(new URL(`../levels/${spec.id}.js`, import.meta.url), `// ${spec.name}. Generated by tools/build-world1.mjs.\nexport default ${body};\n`);
  return level;
}
